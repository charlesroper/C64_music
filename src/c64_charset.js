// Build full 256-character ROM table (256 * 8 bytes)
// Provides complete Commodore 64 Character ROM fidelity:
// - $00..$3F: C64 screen codes (@, A..Z, digits, symbols)
// - $40: Authentic horizontal raster bar
// - $41..$5A: Uppercase A..Z (matching ASCII $41..$5A & Galway SPEED/YYY HUD strings)
// - $5B..$60: Standard brackets and punctuation ([ \ ] ^ _ `)
// - $61..$7A: Authentic C64 lowercase letters (a..z)
// - $7B..$7E: Curly braces and symbols ({ | } ~)
// - $7F: Authentic C64 50% checkerboard / stipple block
// - $80..$FF: Hardware inverse video counterparts (glyph ^ 0xFF)
export const C64_CHAR_ROM = new Uint8Array(256 * 8);

for (let ch = 0; ch < 256; ch++) {
  const baseIdx = ch & 0x7F;
  const inv = (ch & 0x80) ? 0xFF : 0x00;
  let glyph;

  if (baseIdx < 64) {
    glyph = BASE_GLYPHS_64[baseIdx];
  } else if (baseIdx === 0x40) {
    glyph = GLYPH_HORIZ_LINE;
  } else if (baseIdx >= 0x41 && baseIdx <= 0x5A) {
    glyph = BASE_GLYPHS_64[baseIdx - 0x40]; // Uppercase 'A'..'Z'
  } else if (baseIdx === 0x5B) {
    glyph = GLYPH_BRACKET_L;
  } else if (baseIdx === 0x5C) {
    glyph = GLYPH_BACKSLASH;
  } else if (baseIdx === 0x5D) {
    glyph = GLYPH_BRACKET_R;
  } else if (baseIdx === 0x5E) {
    glyph = GLYPH_CARET;
  } else if (baseIdx === 0x5F) {
    glyph = GLYPH_UNDERSCORE;
  } else if (baseIdx === 0x60) {
    glyph = GLYPH_BACKTICK;
  } else if (baseIdx >= 0x61 && baseIdx <= 0x7A) {
    glyph = LOWERCASE_GLYPHS_26[baseIdx - 0x61]; // Lowercase 'a'..'z'
  } else if (baseIdx === 0x7B) {
    glyph = GLYPH_BRACE_L;
  } else if (baseIdx === 0x7C) {
    glyph = GLYPH_VERT_BAR;
  } else if (baseIdx === 0x7D) {
    glyph = GLYPH_BRACE_R;
  } else if (baseIdx === 0x7E) {
    glyph = GLYPH_TILDE;
  } else {
    glyph = GLYPH_CHECKER;
  }

  for (let row = 0; row < 8; row++) {
    C64_CHAR_ROM[ch * 8 + row] = glyph[row] ^ inv;
  }
}

